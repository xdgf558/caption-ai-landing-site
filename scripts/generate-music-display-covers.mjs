// Run before a music production release. Only public, versioned covers are read.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
const origin = 'https://wwwstationcat.org', maxBytes = 5242880;
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
async function read(url, max) {
  let response;
  for(let attempt=0; attempt<3; attempt++) {
    response = await fetch(url, { redirect: 'error', signal: AbortSignal.timeout(30000) });
    if(response.status!==503 || attempt===2) break;
    await response.body?.cancel(); await new Promise(resolve=>setTimeout(resolve,1000));
  }
  assert.equal(response.status, 200, url);
  const reader = response.body.getReader(), parts = []; let length = 0;
  try { while (true) { const { done, value } = await reader.read(); if (done) break;
    length += value.length; assert.ok(length <= max, 'Response exceeds budget'); parts.push(value); }
  } finally { await reader.cancel().catch(() => {}); }
  return Buffer.concat(parts);
}
const catalog = JSON.parse(await read(origin + '/api/music/catalog?locale=zh-Hans', 2097152));
const paths = [...new Set([...catalog.tracks, ...catalog.collections].map(item => item.coverUrl).filter(Boolean))];
assert.ok(paths.length <= 1000); const manifest = {};
await mkdir('public/api/music/__cover-files', { recursive: true });
for (const path of paths) {
  assert.match(path, /^\/api\/music\/(?:tracks\/[a-f0-9-]{36}|collections\/[a-z0-9-]{1,100})\/cover\?v=[1-9][0-9]*$/);
  const original = await read(origin + path, maxBytes);
  const input = sharp(original, { limitInputPixels: 16777216 }), meta = await input.metadata();
  const pipeline = input.resize({ width: 768, height: 768, fit: 'inside', withoutEnlargement: true });
  const bytes = await (meta.hasAlpha ? pipeline.webp({ quality: 82 }) : pipeline.jpeg({ quality: 82 })).toBuffer();
  if (bytes.length >= original.length) continue;
  const sha256 = hash(bytes), extension = meta.hasAlpha ? 'webp' : 'jpg';
  const assetPath = `/api/music/__cover-files/${sha256}.${extension}`;
  await writeFile('public' + assetPath, bytes);
  manifest[hash(original)] = { path: assetPath, sha256, bytes: bytes.length, sourceBytes: original.length,
    contentType: meta.hasAlpha ? 'image/webp' : 'image/jpeg' };
}
await writeFile('src/music/displayCoverManifest.js', '// Generated by npm run build:music:display-covers. No runtime image encoding.\nexport const musicDisplayCoverManifest = Object.freeze(' + JSON.stringify(manifest, null, 2) + ');\n');
console.log(`Prepared ${Object.keys(manifest).length} public display covers.`);
